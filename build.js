#!/usr/bin/env node
// Scans ./Plugins, then generates manifest.json, generated/plugins.json and
// generated/plugin-backgrounds.js. Re-run after adding/removing a plugin, then reload the extension.
const fs = require("fs");
const path = require("path");

const root = __dirname;
const pluginsDir = path.join(root, "Plugins");
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const union = (...lists) => [...new Set(lists.flat().filter(Boolean))];

const manifest = readJson(path.join(root, "manifest.base.json"));
const plugins = [];
const bgLines = [];

const dirs = fs.existsSync(pluginsDir)
  ? fs.readdirSync(pluginsDir, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith(".")).map((d) => d.name).sort()
  : [];

for (const dir of dirs) {
  const mPath = path.join(pluginsDir, dir, "manifest.json");
  if (!fs.existsSync(mPath)) continue;
  let m;
  try { m = readJson(mPath); } catch (e) { console.warn(`skip ${dir}: bad manifest (${e.message})`); continue; }

  const base = `Plugins/${dir}/`;
  const entry = (m.side_panel && m.side_panel.default_path) || (m.action && m.action.default_popup) || m.options_page;
  if (!entry) { console.warn(`skip ${dir}: no popup/side panel page`); continue; }

  const icons = (m.action && m.action.default_icon) || m.icons;
  const icon = icons && (typeof icons === "string" ? icons : icons["16"] || Object.values(icons)[0]);
  plugins.push({ id: dir, name: m.name || dir, version: m.version || "", url: base + entry, icon: icon ? base + icon : null });

  manifest.permissions = union(manifest.permissions, m.permissions);
  manifest.host_permissions = union(manifest.host_permissions, m.host_permissions);
  manifest.optional_permissions = union(manifest.optional_permissions, m.optional_permissions);
  manifest.optional_host_permissions = union(manifest.optional_host_permissions, m.optional_host_permissions);

  for (const cs of m.content_scripts || []) {
    manifest.content_scripts = manifest.content_scripts || [];
    const c = { ...cs };
    if (c.js) c.js = c.js.map((f) => base + f);
    if (c.css) c.css = c.css.map((f) => base + f);
    manifest.content_scripts.push(c);
  }

  const sw = m.background && m.background.service_worker;
  if (sw) {
    if (m.background.type === "module") console.warn(`${dir}: module service workers are not supported; background skipped`);
    else bgLines.push(`load(${JSON.stringify(dir)}, ${JSON.stringify(sw)});`);
  }
}

for (const k of ["optional_permissions", "optional_host_permissions", "host_permissions"]) {
  if (!manifest[k] || !manifest[k].length) delete manifest[k];
}

const bg = `// Generated by build.js - do not edit.
const nativeImport = self.importScripts.bind(self);
let currentBase = "";
// Plugin scripts call importScripts relative to their own folder.
self.importScripts = (...urls) => nativeImport(...urls.map((u) => (/^(\\/|[a-z-]+:)/i.test(u) ? u : currentBase + u)));
function load(dir, file) {
  currentBase = "Plugins/" + dir + "/";
  try { self.importScripts(file); } catch (e) { console.error("[plugin-manager] " + dir + " background failed:", e); }
  currentBase = "";
}
${bgLines.join("\n")}
`;

fs.mkdirSync(path.join(root, "generated"), { recursive: true });
fs.writeFileSync(path.join(root, "generated/plugins.json"), JSON.stringify(plugins, null, 2));
fs.writeFileSync(path.join(root, "generated/plugin-backgrounds.js"), bg);
fs.writeFileSync(path.join(root, "manifest.json"), JSON.stringify(manifest, null, 2));
console.log(`Built ${plugins.length} plugin(s): ${plugins.map((p) => p.name).join(", ") || "none"}`);
